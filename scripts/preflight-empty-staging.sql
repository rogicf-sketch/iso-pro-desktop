-- Preflight v2: recria tabelas legado com colunas alinhadas a prod (staging vazio).
-- So para bootstrap sem Restore. NAO correr em producao.

DROP TABLE IF EXISTS public.usuario_permissoes CASCADE;
DROP TABLE IF EXISTS public.perfil_permissoes CASCADE;
DROP TABLE IF EXISTS public.dispositivos_mobile CASCADE;
DROP TABLE IF EXISTS public.desktop_licencas CASCADE;
DROP TABLE IF EXISTS public.iso_pro_relatorio_snapshot CASCADE;
DROP TABLE IF EXISTS public.usuarios_sistema CASCADE;
DROP TABLE IF EXISTS public.perfis_acesso CASCADE;
DROP TABLE IF EXISTS public.materiais CASCADE;
DROP TABLE IF EXISTS public.iso_pro_snapshot CASCADE;

CREATE TABLE public.perfis_acesso (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo text NOT NULL,
  nome text NOT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id)
);

CREATE TABLE public.usuarios_sistema (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  login text NOT NULL,
  nome text NOT NULL DEFAULT '',
  senha text NOT NULL DEFAULT '',
  perfil_id uuid NOT NULL REFERENCES public.perfis_acesso(id),
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id),
  auth_user_id uuid,
  colaborador_id text
);

CREATE TABLE public.materiais (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL,
  descricao text,
  diametro text,
  disciplina text,
  unidade text,
  peso double precision,
  estoque_minimo double precision,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  ativo boolean NOT NULL DEFAULT true,
  codigo_barras text NOT NULL DEFAULT '',
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id)
);

CREATE TABLE public.usuario_permissoes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  usuario_id uuid NOT NULL,
  modulo text NOT NULL,
  acao text NOT NULL,
  permitido boolean NOT NULL DEFAULT true,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id)
);

CREATE TABLE public.perfil_permissoes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  perfil_id uuid NOT NULL,
  modulo text NOT NULL,
  acao text NOT NULL,
  permitido boolean NOT NULL DEFAULT true,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id)
);

CREATE TABLE public.dispositivos_mobile (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id text NOT NULL,
  nome_aparelho text NOT NULL DEFAULT '',
  usuario_login text NOT NULL DEFAULT '',
  usuario_nome text,
  plataforma text NOT NULL DEFAULT 'android',
  modelo text NOT NULL DEFAULT '',
  versao_app text NOT NULL DEFAULT '',
  autorizado boolean NOT NULL DEFAULT false,
  bloqueado boolean NOT NULL DEFAULT false,
  ultimo_acesso_em timestamptz,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id)
);

CREATE TABLE public.iso_pro_snapshot (
  id text NOT NULL DEFAULT 'default',
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id),
  documentos jsonb,
  PRIMARY KEY (id, tenant_id)
);

CREATE TABLE public.iso_pro_relatorio_snapshot (
  id text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id),
  PRIMARY KEY (id, tenant_id)
);

CREATE TABLE public.desktop_licencas (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  license_id text NOT NULL,
  issued_to text NOT NULL DEFAULT '',
  machine_fingerprint text NOT NULL DEFAULT '',
  machine_label text,
  app_version text,
  status text NOT NULL DEFAULT 'active',
  emitida_em timestamptz NOT NULL DEFAULT now(),
  expira_em timestamptz,
  revogada_em timestamptz,
  motivo_revogacao text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.iso_pro_tenants(id),
  PRIMARY KEY (license_id, tenant_id)
);

