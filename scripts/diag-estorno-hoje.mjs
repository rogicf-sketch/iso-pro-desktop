const pl = typeof snap.payload==='string'?JSON.parse(snap.payload):snap.payload;
const log = pl.atendimentoEstornoLog ?? [];
console.log('estorno log total:', log.length);
for (const e of log.slice(-5)) console.log(JSON.stringify({ data: e.dataEstorno, lote: e.loteNumero, cod: e.codigoMaterial, q: e.quantidadeEstornada }));
